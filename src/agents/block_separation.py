from __future__ import annotations

import json
import os
import subprocess
import sys
import threading
import time
from typing import Any

from src.agents._ui import spinner as _spinner
from src.models.opencode import DEFAULT_OPENCODE_MODEL, opencode_silent
from src.prompts.block_separation_prompt import PROMPT_BLOCK_SEPARATION


SCRIPT_TIMEOUT_S = 300  # hard cap for one generated-script execution


def _word_pages(ocr_csv: str) -> dict[int, int]:
    """Map global word id → page number from the OCR CSV."""
    import csv

    pages: dict[int, int] = {}
    with open(ocr_csv, encoding="utf-8", errors="replace") as f:
        for row in csv.DictReader(f):
            try:
                pages[int(row["id"])] = int(row["page"])
            except (KeyError, ValueError):
                continue
    return pages


def _validate_output(out_dir: str, ocr_csv: str | None = None) -> str | None:
    """Check block_separation.json minimal schema. Returns an error message or None."""
    out_json = os.path.join(out_dir, "block_separation.json")
    try:
        with open(out_json, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        return f"block_separation.json could not be read: {exc}"
    pages = data.get("pages")
    if not isinstance(pages, list) or not pages:
        return 'block_separation.json must have a non-empty "pages" list'
    for entry in pages:
        if not isinstance(entry, dict) or "blocks" not in entry:
            return 'every entry in "pages" must be an object with a "blocks" list'

    # ── page-locality invariant ───────────────────────────────────────────────
    # A block emitted under page P must contain only page-P words. A script
    # that globs "everything until the next header band" across pages builds a
    # mega-block on the header's page that swallows the rest of the document
    # (rows that continue on later pages must be emitted as continuation
    # blocks on THEIR page instead). Enforce it so the OpenCode retry loop gets
    # the violation as feedback rather than shipping the bug to test pages.
    if ocr_csv and os.path.isfile(ocr_csv):
        word_pages = _word_pages(ocr_csv)
        for entry in pages:
            page_num = entry.get("page")
            for block in entry.get("blocks", []):
                foreign = sorted({
                    word_pages[w["id"]]
                    for w in block.get("words", [])
                    if w.get("id") in word_pages and word_pages[w["id"]] != page_num
                })
                if foreign:
                    return (
                        f"block {block.get('block_id')} is emitted under page {page_num} "
                        f"but contains words from page(s) {foreign}. Blocks are PAGE-LOCAL: "
                        "a block may only contain words of its own page. Rows of a table "
                        "that continue onto later pages must be emitted as separate "
                        "continuation blocks of the same node on each of those pages — "
                        "never merged into one block or given synthesized cross-page "
                        "y-coordinates."
                    )
    return None


def _run_script(script_path: str, ocr_csv: str, out_dir: str) -> str | None:
    """Execute the generated script and validate its output. Returns an error message or None."""
    try:
        result = subprocess.run(
            [sys.executable, script_path, ocr_csv, out_dir],
            capture_output=True,
            text=True,
            timeout=SCRIPT_TIMEOUT_S,
        )
    except subprocess.TimeoutExpired:
        return f"block_separation.py timed out after {SCRIPT_TIMEOUT_S}s"
    if result.returncode != 0:
        return f"block_separation.py failed (exit {result.returncode}):\n{result.stderr}"
    return _validate_output(out_dir, ocr_csv)


def run_block_separation_node(state: dict[str, Any]) -> dict[str, Any]:
    """Execute the block_separation.py script generated by block_separation_node.

    Reads:
        state["pdf_path"]     – used to derive the train directory
        state["ocr_csv_path"] – OCR CSV path passed as first arg to the script

    Side-effect:
        Runs block_separation.py, which writes block_separation.json into train_dir.
    """
    train_dir   = os.path.dirname(state["pdf_path"])
    script_path = os.path.join(train_dir, "block_separation.py")
    ocr_csv     = state.get("build_ocr_csv_path") or state["ocr_csv_path"]

    t0 = time.time()
    error = _run_script(script_path, ocr_csv, train_dir)
    duration = time.time() - t0

    if error is not None:
        raise RuntimeError(error)

    return {"cost": [{"phase": "run_block_separation", "duration_s": round(duration, 3)}]}


def block_separation_node(state: dict[str, Any]) -> dict[str, Any]:
    """Ask OpenCode to write a block-separation script for the inferred template.

    After each OpenCode attempt the generated script is executed and its output
    validated; failures are fed back into the prompt for the next attempt
    (up to 3 attempts).

    Reads:
        state["template"]       – list of template node dicts from template_inference.
        state["metadata"]       – metadata patterns from template_inference.
        state["ocr_csv_path"]   – path to the full OCR CSV.
        state["agent_space"]    – workspace used to locate the train directory.

    Writes:
        Nothing new to state; side-effect is the script written inside agent_space.
    """
    template_json = json.dumps(
        [node for node in state["template"] if node.get("type") in ("table", "kv")],
        indent=2,
    )
    metadata_json = json.dumps(state.get("metadata", []), indent=2)
    ocr_csv_path = state.get("build_ocr_csv_path") or state["ocr_csv_path"]
    train_dir = os.path.dirname(state["pdf_path"])
    script_path = os.path.join(train_dir, "block_separation.py")

    base_prompt = PROMPT_BLOCK_SEPARATION(ocr_csv_path, template_json, metadata_json)
    prompt = base_prompt

    debug_dir = os.path.join(os.path.dirname(state["agent_space"]), "debug")

    MAX_ATTEMPTS = 3
    input_t, output_t, total_t = None, None, None
    duration, last_error = 0.0, ""

    print(
        "block_separation_node: generating the block separator with OpenCode...",
        flush=True,
    )

    for attempt in range(1, MAX_ATTEMPTS + 1):
        label = "block_separation" if attempt == 1 else f"block_separation (retry {attempt - 1})"
        stop_event = threading.Event()
        spinner_result: dict = {}
        spinner_thread = threading.Thread(
            target=_spinner,
            args=(label, stop_event, spinner_result),
            daemon=True,
        )
        spinner_thread.start()

        t0 = time.time()
        log_path = os.path.join(debug_dir, f"block_separation_{attempt}.log") if state.get("save_log") else None
        returncode, input_t, output_t, total_t = opencode_silent(
            prompt, train_dir, task="block_separation",
            model=(
                state.get("hard_model")
                or state.get("opencode_model")
                or DEFAULT_OPENCODE_MODEL
            ),
            caveman=state.get("use_caveman", False), log_path=log_path,
        )
        duration = time.time() - t0

        # run the generated script and validate its output
        last_error = None
        if returncode != 0:
            last_error = f"OpenCode exited {returncode}"
        elif not os.path.isfile(script_path):
            last_error = "OpenCode did not produce block_separation.py"
        else:
            last_error = _run_script(script_path, ocr_csv_path, train_dir)

        shown_t = (input_t or 0) + (output_t or 0) + (total_t or 0) or None
        spinner_result["tokens"] = shown_t
        spinner_result["ok"] = last_error is None
        stop_event.set()
        spinner_thread.join(timeout=0.5)

        if last_error is None:
            break
        print(f"  block_separation attempt {attempt} failed: {last_error}")
        prompt = (
            base_prompt
            + f"\n\nA PREVIOUS ATTEMPT AT THIS TASK FAILED WITH:\n{last_error}\n"
            "Fix block_separation.py so it runs cleanly and produces valid output."
        )

    if last_error is not None:
        raise RuntimeError(f"block_separation failed after {MAX_ATTEMPTS} attempt(s): {last_error}")

    cost_entry: dict = {"phase": "block_separation", "duration_s": round(duration, 3)}
    if input_t is not None:
        cost_entry["input_tokens"] = input_t
    if output_t is not None:
        cost_entry["output_tokens"] = output_t
    if total_t is not None:
        cost_entry["total_tokens"] = total_t

    return {"cost": [cost_entry]}
